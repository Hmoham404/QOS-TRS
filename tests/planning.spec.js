import {test,expect} from '@playwright/test';
test('Quantité planifiée, brouillon après navigation et rechargement, sauvegarde et export',async({page})=>{
  await page.goto('/');
  await expect(page.getByLabel('Mot de passe',{exact:true})).toHaveCount(0);
  await page.getByRole('button',{name:'Saisie de production',exact:true}).click();
  await page.getByLabel('Date de production').fill('2026-10-16');
  await page.getByLabel('Quantité planifiée',{exact:true}).fill('6000');
  await page.getByLabel('Quantité conforme',{exact:true}).fill('5000');
  await page.getByLabel('Commentaire du poste').fill('Plan PWA');
  await expect(page.locator('.draft-status')).toBeVisible();
  await page.getByRole('button',{name:'Vue d’ensemble',exact:true}).click();
  await page.reload();
  await page.getByRole('button',{name:'Saisie de production',exact:true}).click();
  await expect(page.getByLabel('Quantité planifiée',{exact:true})).toHaveValue('6000');
  await expect(page.getByLabel('Quantité conforme',{exact:true})).toHaveValue('5000');
  await page.getByRole('button',{name:'Enregistrer le relevé',exact:true}).click();
  await expect(page.getByRole('status')).toContainText('Relevé enregistré');
  const records=await page.evaluate(()=>JSON.parse(localStorage.getItem('qos-injection-v1')).records);
  expect(records.find(r=>r.notes==='Plan PWA').planned_qty).toBe(6000);
  await page.getByRole('textbox',{name:'Rechercher un relevé'}).fill('Plan PWA');
  await expect(page.locator('tbody tr')).toContainText('6\u202f000');
  const downloading=page.waitForEvent('download');await page.getByRole('button',{name:'Exporter CSV'}).click();
  const download=await downloading;const stream=await download.createReadStream();let csv='';for await(const chunk of stream)csv+=chunk;
  expect(csv).toContain('Quantité planifiée');expect(csv).toContain(';"6000"');
  await page.getByRole('button',{name:'Modifier',exact:true}).click();
  await page.getByLabel('Quantité planifiée',{exact:true}).fill('0');
  await page.getByRole('button',{name:'Enregistrer les modifications'}).click();
  await expect(page.getByRole('status')).toContainText('Relevé enregistré');
  expect(await page.evaluate(()=>Object.keys(localStorage).filter(k=>k.startsWith('qos-draft-v1:')))).toEqual([]);
});
