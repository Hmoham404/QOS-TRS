// Share catalogue references without moving workshop production history.
// Initial timings come from Metallization and remain editable in Assembly.
export function assemblyArticles(articles) {
  return articles.filter(article => article.active !== false).map(article => ({
    ...article,
    id: ((parseInt(article.id.slice(0, 8), 16) ^ 0x03000000) >>> 0).toString(16).padStart(8, '0') + article.id.slice(8),
    department: 'assembly', name: article.name, cavities: 1,
    mold_cycle_seconds: article.mold_cycle_seconds / article.cavities,
    trs_target: .8, dle_target: .8,
  }));
}

export function withAssemblyArticles(data, metalArticles) {
  const source = assemblyArticles(metalArticles);
  // Repair only the exact names generated by the earlier sorting-only catalogue.
  // Preserve IDs, archives, user renames, parameters and production snapshots.
  const articles = data.articles.map(existing => {
    const article = source.find(item => item.id === existing.id);
    return article && existing.name === `Tri · ${article.name.slice(0, 154)}`
      ? {...existing, name: article.name} : existing;
  });
  const missing = source.filter(article =>
    !data.articles.some(existing => existing.id === article.id || existing.code.toLowerCase() === article.code.toLowerCase()));
  return {...data, articles: [...articles, ...missing]};
}
