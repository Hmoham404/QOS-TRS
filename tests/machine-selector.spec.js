import { test, expect } from '@playwright/test';
import { readFileSync } from 'node:fs';
import { aggregate, percent, formatNumber as num } from '../src/domain.js';

const seed = JSON.parse(readFileSync(new URL('../src/seed.json', import.meta.url), 'utf8'));
const dayRows = seed.records.filter(row => row.date === '2026-10-08');
const entered = seed.presses.find(press => dayRows.some(row => row.press_id === press.id));
const empty = seed.presses.find(press => !dayRows.some(row => row.press_id === press.id));

test('La liste distingue les machines saisies et filtre les indicateurs, les courbes et le total', async ({ page }) => {
  const errors = [];
  page.on('pageerror', error => errors.push(error.message));
  await page.clock.setFixedTime(new Date('2026-10-08T12:00:00Z'));
  await page.goto('/', { waitUntil: 'domcontentloaded' });
  await page.locator('.brand').click();
  const card = page.locator('.comparison-card[data-department="injection"]');
  await card.locator('.comparison-scope-trigger').click();
  await card.getByRole('option', {name: 'Injection machines', exact: true}).click();
  const trigger = card.getByRole('button', { name: 'Machines · Injection', exact: true });
  await expect(page.locator('.comparison-factory-metrics')).toHaveAttribute('aria-busy', 'false');
  const factoryValues = await page.locator('.comparison-intro dd').allTextContents();
  await trigger.click();
  const options = card.getByRole('option');
  await expect(options).toHaveCount(seed.presses.length + 1);
  const withRecords = card.locator(`[data-machine-id="injection:${entered.id}"]`);
  const withoutRecords = card.locator(`[data-machine-id="injection:${empty.id}"]`);
  await expect(withRecords).toHaveCSS('font-weight', '800');
  await expect(withoutRecords).toHaveCSS('font-weight', '400');
  expect(await card.locator('.comparison-machine-options').evaluate(element => element.scrollHeight > element.clientHeight)).toBe(true);
  await card.screenshot({ path: '.runtime/machine-selector-desktop.png' });
  await withRecords.click();
  const selectedRows = dayRows.filter(row => row.press_id === entered.id);
  await expect(card.locator('.comparison-count')).toHaveText(`${num(selectedRows.length)} relevés`);
  await expect(card.locator('.comparison-metric.primary strong')).toHaveText(percent(aggregate(selectedRows).trs));
  await expect(trigger).toContainText(entered.name);
  await expect(page.locator('.comparison-intro dd')).toHaveText(factoryValues);
  await card.getByRole('button', { name: 'Disponibilité · Injection · Voir la courbe', exact: true }).click();
  const dialog = page.getByRole('dialog');
  await expect(dialog.locator('.comparison-index')).toHaveText(`Injection · Injection machines · ${entered.name}`);
  await dialog.getByRole('button', { name: 'Fermer', exact: true }).click();
  await trigger.click();
  await withoutRecords.click();
  await expect(card.locator('.comparison-count')).toHaveText('0 relevés');
  await expect(card.locator('.comparison-metric.primary strong')).toHaveText('—');
  await expect(trigger).toHaveCSS('font-weight', '400');
  await trigger.click();
  await card.getByRole('option', { name: /Total/ }).click();
  await expect(card.locator('.comparison-count')).toHaveText(`${num(dayRows.length)} relevés`);
  await expect(card.locator('.comparison-metric.primary strong')).toHaveText(percent(aggregate(dayRows).trs));
  await page.getByLabel('Date analysée').fill('2026-10-09');
  await trigger.click();
  await expect(card.locator('.comparison-machine-option[data-has-records=true]')).toHaveCount(new Set(seed.records.map(row => row.press_id)).size + 1);
  await expect(withRecords).toHaveCSS('font-weight', '800');
  await expect(withRecords).toContainText('0 relevés');
  await expect(withoutRecords).toHaveCSS('font-weight', '400');
  await page.keyboard.press('Escape');
  await expect(trigger).toBeFocused();
  await trigger.press('ArrowDown');
  await page.keyboard.press('ArrowDown');
  await page.keyboard.press('Enter');
  await expect(trigger).toContainText(seed.presses[0].name);
  await expect(trigger).toHaveCSS('font-weight', '800');
  await page.setViewportSize({ width: 390, height: 844 });
  await trigger.click();
  await expect(card.getByRole('listbox')).toBeVisible();
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true);
  await card.screenshot({ path: '.runtime/machine-selector-mobile.png' });
  expect(errors).toEqual([]);
});
