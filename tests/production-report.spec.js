import { test, expect } from '@playwright/test';

test('Rapport : mois civil, pointage vide, DLE, isolation des périodes et fermeture au clavier', async ({ page }) => {
  const errors = [];
  page.on('pageerror', error => errors.push(error.message));
  await page.goto('/');
  const trigger = page.getByRole('button', {name:'Rapport de production',exact:true});
  await trigger.click();
  const dialog = page.getByRole('dialog', {name:'Rapport de production'});
  await expect(dialog).toBeVisible();
  await dialog.getByRole('button',{name:'Semaine',exact:true}).click();
  await dialog.getByLabel('Date du rapport').fill('2027-01-01');
  await expect(dialog.locator('.pr-period')).toContainText('28 décembre 2026 — 03 janvier 2027');
  await dialog.getByRole('button',{name:'Mois',exact:true}).click();
  await dialog.getByLabel('Mois du rapport').fill('2026-10');
  await expect(dialog.locator('.pr-period')).toContainText('01 octobre 2026 — 31 octobre 2026');
  await expect(dialog.getByTestId('delivered-time')).not.toContainText('—');
  const pointage = dialog.getByLabel('Temps de pointage (h)');
  await expect(pointage).toHaveValue('');
  await expect(dialog.getByTestId('report-dle')).toHaveText('—');
  const expected = await page.evaluate(async () => {
    const {productionReport} = await import('/src/production-report.js');
    const {loadData} = await import('/src/data.js');
    const {DEPARTMENT_IDS} = await import('/src/departments.js');
    return productionReport(await Promise.all(DEPARTMENT_IDS.map(async id => ({...await loadData(id),department:id}))), '2026-10-01', '2026-10-31').hours;
  });
  await pointage.fill('100');
  await expect(dialog.getByTestId('report-dle')).toHaveText(new Intl.NumberFormat('fr-FR',{minimumFractionDigits:1,maximumFractionDigits:1}).format(expected) + ' %');
  await dialog.getByLabel('Mois du rapport').fill('2028-02');
  await expect(dialog.locator('.pr-period')).toContainText('29 février 2028');
  await expect(pointage).toHaveValue('');
  await dialog.getByLabel('Mois du rapport').fill('2026-10');
  await expect(pointage).toHaveValue('100');
  await pointage.fill('0');
  await expect(pointage).toHaveAttribute('aria-invalid','true');
  await expect(dialog.getByTestId('report-dle')).toHaveText('—');
  await page.setViewportSize({width:390,height:844});
  await expect(dialog).toBeVisible();
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true);
  await page.screenshot({path:'.runtime/production-report-mobile.png'});
  await page.setViewportSize({width:1440,height:1100});
  await page.screenshot({path:'.runtime/production-report-desktop.png'});
  await page.evaluate(() => document.documentElement.dataset.theme = 'dark');
  await page.screenshot({path:'.runtime/production-report-dark.png'});
  await page.keyboard.press('Escape');
  await expect(dialog).not.toBeVisible();
  await expect(trigger).toBeFocused();
  await trigger.click();
  await expect(page.getByRole('dialog').getByLabel('Temps de pointage (h)')).toHaveValue('');
  expect(errors).toEqual([]);
});
