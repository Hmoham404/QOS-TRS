import {test,expect} from '@playwright/test';

test('8 h puis 12 h : calcul en direct, reprise et historique inchangé',async({page})=>{
  await page.goto('/');
  const entry=()=>page.getByRole('button',{name:'Saisie de production',exact:true}).click();
  await entry();
  const required=page.locator('.shift-time-fields .auto-field').filter({hasText:'Temps requis'});
  await expect(required).toContainText('450,0');
  await expect(page.getByLabel('Pause',{exact:true})).toHaveValue('20');
  await expect(page.getByLabel('Réunion 5 min',{exact:true})).toHaveValue('5');
  await expect(page.getByLabel('5S',{exact:true})).toHaveValue('5');
  await expect(page.locator('.shift-time-overview')).toContainText('Durée du poste × 60 − Pause − Réunion 5 min − 5S');
  for (const label of ['Pause','Réunion 5 min','5S']) await page.getByLabel(label,{exact:true}).fill('0');
  await expect(required).toContainText('480,0');
  await page.getByLabel('Pause',{exact:true}).fill('20');
  await page.getByLabel('Réunion 5 min',{exact:true}).fill('5');
  await page.getByLabel('5S',{exact:true}).fill('5');
  await page.getByLabel('Date de production').fill('2026-11-19');
  await page.getByLabel('Commentaire du poste').fill('Poste 8 h conservé');
  await page.getByRole('button',{name:'Enregistrer le relevé',exact:true}).click();
  await expect(page.getByRole('status')).toContainText('Relevé enregistré');
  await entry();
  await page.getByLabel('Durée du poste').fill('12');
  await expect(required).toContainText('690,0');
  await page.getByLabel('Pause',{exact:true}).fill('30');
  await expect(required).toContainText('680,0');
  await page.getByLabel('Arrêts planifiés',{exact:true}).fill('15');
  await expect(required).toContainText('665,0');
  await expect(page.locator('.shift-time-overview .auto-field')).toContainText('680,0');
  await page.getByLabel('Date de production').fill('2026-11-26');
  await page.getByRole('button',{name:'Enregistrer le relevé',exact:true}).click();
  await expect(page.getByRole('status')).toContainText('Relevé enregistré');
  await page.reload(); await entry();
  await expect(page.getByLabel('Durée du poste')).toHaveValue('12');
  await expect(page.getByLabel('Pause',{exact:true})).toHaveValue('30');
  await page.getByRole('button',{name:'Historique des relevés',exact:true}).click();
  await page.getByRole('textbox',{name:'Rechercher un relevé'}).fill('Poste 8 h conservé');
  await page.getByRole('button',{name:'Modifier',exact:true}).click();
  await expect(page.getByLabel('Durée du poste')).toHaveValue('8');
  await expect(page.getByLabel('Pause',{exact:true})).toHaveValue('20');
  await expect(required).toContainText('450,0');
  await page.screenshot({path:'.runtime/shift-time-desktop.png',fullPage:true});
  await page.setViewportSize({width:390,height:844});
  expect(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth)).toBe(true);
  await page.screenshot({path:'.runtime/shift-time-mobile.png',fullPage:true});
});

test('Le journal déduit uniquement les arrêts supplémentaires de l’ouverture nette',async({page})=>{
  await page.goto('/');
  await page.getByRole('button',{name:'Saisie de production',exact:true}).click();
  await page.getByRole('checkbox',{name:/Utiliser les arrêts horodatés/}).check();
  await expect(page.getByLabel('Pause',{exact:true})).toHaveValue('20');
  await page.getByRole('button',{name:'Minutes depuis le début',exact:true}).click();
  await page.getByRole('button',{name:'Ajouter un arrêt',exact:true}).click();
  await page.getByLabel('Début arrêt 1',{exact:true}).fill('60');
  await page.getByLabel('Fin arrêt 1',{exact:true}).fill('90');
  await page.getByLabel('Catégorie arrêt 1',{exact:true}).selectOption('planned');
  await expect(page.locator('.shift-time-fields .auto-field').filter({hasText:'Temps requis'})).toContainText('420,0');
  await expect(page.locator('.machine-time')).toContainText('420,0');
});
